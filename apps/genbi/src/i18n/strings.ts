type Leaves<T> = T extends object
  ? { [K in keyof T]: `${K & string}${'' | `.${Leaves<T[K]>}`}` }[keyof T]
  : never;

export type StringKey = Leaves<typeof strings>;

/** Dot-path lookup into the strings tree. Returns the key itself if missing. */
export function t(key: StringKey): string {
  const value = key
    .split('.')
    .reduce<unknown>((acc, part) => (acc as Record<string, unknown>)?.[part], strings);
  return typeof value === 'string' ? value : key;
}
